import { NavLink, Outlet, useNavigate } from 'react-router-dom'
import { useAuth } from '../context/AuthContext'
import '../admin.css'

const links = [
  { to: '/admin', label: 'Dashboard', end: true, icon: <DashboardIcon /> },
  { to: '/admin/contacts', label: 'Inquiries', icon: <InboxIcon /> },
  { to: '/admin/services', label: 'Services', icon: <ServicesIcon /> },
  { to: '/admin/gallery', label: 'Gallery', icon: <GalleryIcon /> },
  { to: '/admin/settings', label: 'Settings', icon: <SettingsIcon /> },
  { to: '/admin/users', label: 'Admin Users', icon: <UsersIcon /> },
]

export default function AdminLayout() {
  const { user, logout } = useAuth()
  const navigate = useNavigate()

  const handleLogout = () => {
    logout()
    navigate('/admin/login', { replace: true })
  }

  return (
    <div className="admin">
      <aside className="admin__sidebar">
        <div className="admin__brand">
          <span className="admin__brand-name">RUKN AL HARIR</span>
          <span className="admin__brand-sub">Admin Panel</span>
        </div>

        <nav className="admin__nav">
          {links.map((l) => (
            <NavLink
              key={l.to}
              to={l.to}
              end={l.end}
              className={({ isActive }) => `admin__nav-link${isActive ? ' is-active' : ''}`}
            >
              {l.icon}
              {l.label}
            </NavLink>
          ))}
        </nav>

        <div className="admin__sidebar-footer">
          <div className="admin__user">
            <span className="admin__user-name">{user?.name}</span>
            <span className="admin__user-email">{user?.email}</span>
          </div>
          <button className="admin__logout" onClick={handleLogout}>
            Log out
          </button>
        </div>
      </aside>

      <main className="admin__content">
        <Outlet />
      </main>
    </div>
  )
}

